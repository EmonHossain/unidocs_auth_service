ALTER TABLE organization_membership ADD CONSTRAINT uq_org_member_assignment_anchor UNIQUE(organization_id,id,account_id);
CREATE TABLE group_membership (
 id BINARY(16) NOT NULL PRIMARY KEY,
 organization_id BINARY(16) NOT NULL,
 group_id BINARY(16) NOT NULL,
 account_id BINARY(16) NOT NULL,
 organization_membership_id BINARY(16) NOT NULL,
 role VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 membership_type VARCHAR(32) NOT NULL,
 source VARCHAR(32) NOT NULL,
 status VARCHAR(32) NOT NULL,
 valid_from DATETIME(6) NOT NULL,
 valid_until DATETIME(6) NULL,
 version BIGINT NOT NULL,
 assigned_by_account_id BINARY(16) NOT NULL,
 assignment_request_id BINARY(16) NOT NULL,
 assignment_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revoked_at DATETIME(6) NULL,
 revoked_by_account_id BINARY(16) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 active_organization_membership_id BINARY(16) GENERATED ALWAYS AS(IF(status='ACTIVE',organization_membership_id,NULL)) STORED,
 CONSTRAINT fk_assignment_group FOREIGN KEY(organization_id,group_id) REFERENCES iam_group(organization_id,id),
 CONSTRAINT fk_assignment_account FOREIGN KEY(account_id) REFERENCES user_account(id),
 CONSTRAINT fk_assignment_organization_membership FOREIGN KEY(organization_id,organization_membership_id,account_id) REFERENCES organization_membership(organization_id,id,account_id),
 CONSTRAINT uq_group_assignment_request UNIQUE(organization_id,assigned_by_account_id,assignment_request_id),
 CONSTRAINT uq_group_active_assignment UNIQUE(group_id,active_organization_membership_id),
 CONSTRAINT chk_group_member_status CHECK(status IN('ACTIVE','REVOKED')),
 CONSTRAINT chk_group_member_type CHECK((membership_type='PERMANENT' AND valid_until IS NULL) OR (membership_type='TEMPORARY' AND valid_until IS NOT NULL)),
 CONSTRAINT chk_group_member_source CHECK(source='ORGANIZATION_ASSIGNMENT'),
 CONSTRAINT chk_group_member_window CHECK(valid_until IS NULL OR valid_until>valid_from),
 CONSTRAINT chk_group_member_version CHECK(version>=1),
 CONSTRAINT chk_group_member_revocation CHECK((status='ACTIVE' AND revoked_at IS NULL AND revoked_by_account_id IS NULL) OR (status='REVOKED' AND revoked_at IS NOT NULL AND revoked_by_account_id IS NOT NULL)),
 INDEX ix_group_member_catalog(organization_id,group_id,id),
 INDEX ix_group_member_account(organization_id,account_id,status,id)
);
